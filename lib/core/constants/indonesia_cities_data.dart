  static List<String> get allProvinces {
    final set = <String>{};
    for (final c in allCities) {
      set.add(c.province);
    }
    final list = set.toList();
    list.sort();
    return list;
  }

  /// Mencari kota/kabupaten dengan query pencarian (misal: "IN").
  /// Algoritma pencarian:
  /// 1. Prioritas utama: Nama kota yang diawali dengan query (prefix match)
  /// 2. Prioritas kedua: Nama kota yang mengandung query
  /// 3. Prioritas ketiga: Nama provinsi yang mengandung query
  static List<IndonesiaCity> searchCities(
    String query, {
    String? provinceFilter,
  }) {
    final cleanQuery = query.trim().toLowerCase();

    var filtered = allCities;
    if (provinceFilter != null &&
        provinceFilter.isNotEmpty &&
        provinceFilter != 'Semua Provinsi') {
      filtered = filtered.where((c) => c.province == provinceFilter).toList();
    }

    if (cleanQuery.isEmpty) {
      return filtered;
    }

    final prefixMatches = <IndonesiaCity>[];
    final containsMatches = <IndonesiaCity>[];
    final provinceMatches = <IndonesiaCity>[];

    for (final c in filtered) {
      final nameLower = c.name.toLowerCase();
      final provLower = c.province.toLowerCase();

      if (nameLower.startsWith(cleanQuery)) {
        prefixMatches.add(c);
      } else if (nameLower.contains(cleanQuery)) {
        containsMatches.add(c);
      } else if (provLower.contains(cleanQuery)) {
        provinceMatches.add(c);
      }
    }

    return [...prefixMatches, ...containsMatches, ...provinceMatches];
  }
